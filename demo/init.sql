-- ==========================================
-- 1. СОЗДАНИЕ ТАБЛИЦ
-- ==========================================

CREATE TABLE dbo.[Организация] (
    [Идентификатор] UNIQUEIDENTIFIER PRIMARY KEY, 
    [Название] NVARCHAR(255)
);

CREATE TABLE dbo.[Должности] (
    [Идентификатор] INT PRIMARY KEY, 
    [Название] NVARCHAR(255)
);

CREATE TABLE dbo.[LifeCycleState] (
    [ID] UNIQUEIDENTIFIER PRIMARY KEY, 
    [Name] NVARCHAR(250) NOT NULL
);

CREATE TABLE dbo.[Подразделение] (
    [Идентификатор] UNIQUEIDENTIFIER PRIMARY KEY, 
    [Название] NVARCHAR(255) NOT NULL, 
    [ИД подразделения] UNIQUEIDENTIFIER
);

CREATE TABLE dbo.[Пользователи] (
    [Идентификатор] INT PRIMARY KEY, 
    [IMObjID] UNIQUEIDENTIFIER NOT NULL,[Имя] NVARCHAR(100), 
    [Отчество] NVARCHAR(100), 
    [Фамилия] NVARCHAR(100), 
    [FullName] NVARCHAR(311), 
    [ИД подразделения] UNIQUEIDENTIFIER, 
    [ИД комнаты] INT, 
    [ИД должности] INT,[Телефон] NVARCHAR(100), 
    [ИД рабочего места] INT
);

CREATE TABLE dbo.[Здание] (
    [Идентификатор] INT PRIMARY KEY, 
    [Название] NVARCHAR(255),[ИД подразделения] UNIQUEIDENTIFIER
);

CREATE TABLE dbo.[Этаж] (
    [Идентификатор] INT PRIMARY KEY, 
    [Название] NVARCHAR(255),
    [ИД здания] INT, 
    [ИД подразделения] UNIQUEIDENTIFIER
);

CREATE TABLE dbo.[Типы комнат] (
    [Идентификатор] INT PRIMARY KEY, 
    [Название] NVARCHAR(255)
);

CREATE TABLE dbo.[Комната] ([Идентификатор] INT PRIMARY KEY, 
    [Название] NVARCHAR(255),[ИД типа] INT, 
    [ИД этажа] INT,[ИД подразделения] UNIQUEIDENTIFIER
);

CREATE TABLE dbo.[Рабочее место] (
    [Идентификатор] INT PRIMARY KEY, 
    [Название] NVARCHAR(255), 
    [ИД комнаты] INT, 
    [ИД подразделения] UNIQUEIDENTIFIER
);

CREATE TABLE dbo.[Производители] (
    [Идентификатор] INT PRIMARY KEY, 
    [Название] NVARCHAR(255)
);

CREATE TABLE dbo.[ProductCatalogType] (
    [ID] UNIQUEIDENTIFIER PRIMARY KEY, 
    [Name] NVARCHAR(500) NOT NULL, 
    [Removed] BIT NOT NULL, 
    [ProductCatalogTemplateID] INT NOT NULL
);

CREATE TABLE dbo.[Типы оконечного оборудования] (
    [Идентификатор] INT PRIMARY KEY, 
    [Название] NVARCHAR(255), 
    [ИД производителя] INT, 
    [ProductCatalogTypeID] UNIQUEIDENTIFIER NOT NULL, 
    [ProductNumber] NVARCHAR(250), 
    [Note] NVARCHAR(255), 
    [Removed] BIT NOT NULL
);

CREATE TABLE dbo.[Оконечное оборудование] (
    [Идентификатор] INT PRIMARY KEY,
    [Название] NVARCHAR(255),
    [Инвентарный номер] NVARCHAR(50), 
    [SerialNumber] NVARCHAR(255), 
    [ИД типа ОО] INT, 
    [ИД рабочего места] INT,
    [ИД комнаты] INT, 
    [Примечание] NVARCHAR(1000),
    [Removed] BIT NOT NULL, 
    [DateRemoved] SMALLDATETIME, 
    [AssetTag] NVARCHAR(255), 
    [Code] NVARCHAR(50), 
    [Description] VARCHAR(250)
);

CREATE TABLE dbo.[Asset] (
    [ID] UNIQUEIDENTIFIER NOT NULL,
    [DeviceID] INT, 
    [LifeCycleStateID] UNIQUEIDENTIFIER, 
    [DateReceived] DATETIME, 
    [IsWorking] BIT NOT NULL, 
    [UtilizerID] UNIQUEIDENTIFIER,
    [UtilizerClassID] INT, 
    [Cost] DECIMAL(12,2), 
    [UserField1] NVARCHAR(255), 
    [UserField3] NVARCHAR(255),
    [DateInquiry] DATETIME, 
    [AppointmentDate] DATETIME, 
    [DateAnnuled] DATETIME
);

CREATE TABLE dbo.[AdapterType] ([AdapterTypeID] UNIQUEIDENTIFIER PRIMARY KEY,
    [ProductCatalogTypeID] UNIQUEIDENTIFIER NOT NULL, 
    [VendorID] INT NOT NULL, 
    [Name] NVARCHAR(255) NOT NULL, 
    [Parameters] NVARCHAR(255), 
    [Note] NVARCHAR(255), 
    [ProductNumber] NVARCHAR(250), 
    [Removed] BIT NOT NULL
);

CREATE TABLE dbo.[Adapter] ([AdapterID] UNIQUEIDENTIFIER PRIMARY KEY, 
    [TerminalDeviceID] INT NOT NULL,
    [Name] NVARCHAR(200), 
    [SerialNo] NVARCHAR(255),[AdapterTypeID] UNIQUEIDENTIFIER, 
    [Note] NVARCHAR(1000)
);
GO

